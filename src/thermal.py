"""Shelter Thermal Dynamics & Battery Temperature Coupling (src/thermal.py).

Implements the two-node thermal model specified in Architecture v3.3 (Sections 4.3 & 11):
  1. Shelter node: dT_in/dt = (P_heat - UA * (T_in - T_out) - Q_hvac) / C_th_shelter
  2. Battery node: dT_batt/dt = (P_batt_loss - hA_batt * (T_batt - T_in)) / C_th_batt

Parameters conform to Section 11 Parameter Freeze:
  - UA = 40.0 W/K (shelter envelope conductance)
  - C_th_shelter = 250,000 J/K (250 kJ/K air + equipment + walls)
  - C_th_batt = 240,000 J/K for VRLA (100,000 J/K for LFP)
  - hA_batt = 18.0 W/K (battery-to-shelter heat transfer)
  - T_setpoint = 25.0 °C (HVAC target temperature)
  - T_warn = 40.0 °C (IEEE derating threshold)
  - T_crit = 50.0 °C (Safety arbiter emergency shutdown threshold)
"""

from __future__ import annotations
import math
from dataclasses import dataclass

UA_SHELTER = 40.0            # W/K shelter envelope conductance
C_TH_SHELTER = 250_000.0     # J/K (250 kJ/K) shelter thermal capacity
C_TH_BATT_VRLA = 240_000.0   # J/K (240 kJ/K) 200Ah VRLA bank thermal mass
C_TH_BATT_LFP = 100_000.0    # J/K (100 kJ/K) 15S LFP pack thermal mass
HA_BATT = 18.0               # W/K battery-to-shelter thermal coupling
T_SETPOINT = 25.0            # °C HVAC cooling setpoint
T_WARN = 40.0                # °C IEEE derating & dry-out warning threshold
T_CRIT = 50.0                # °C Emergency thermal shutdown threshold


def ambient_temperature(hour: float, base_temp: float = 34.0, amplitude: float = 8.0) -> float:
    """Diurnal Iranian summer ambient temperature profile (°C).
    Peaks at ~15:00, minimum at ~03:00.
    """
    return base_temp + amplitude * math.sin(2.0 * math.pi * (hour - 9.0) / 24.0)


@dataclass
class ShelterThermalModel:
    ua: float = UA_SHELTER
    c_shelter: float = C_TH_SHELTER
    ha_batt: float = HA_BATT
    t_setpoint: float = T_SETPOINT
    t_shelter: float = T_SETPOINT
    t_batt: float = T_SETPOINT
    hvac_kw: float = 3.5  # 3.5 kW telecom shelter split AC capacity

    def step(
        self,
        dt_s: float,
        grid_up: bool,
        p_in_heat_w: float,
        p_batt_heat_w: float,
        t_amb: float,
        c_batt: float = C_TH_BATT_VRLA,
    ) -> tuple[float, float]:
        """Advances shelter air and battery temperatures by dt_s seconds.

        p_in_heat_w: heat generated by BBU, transport, rectifiers inside shelter (W).
        p_batt_heat_w: internal Joule (I^2*R) or float charge reaction heat in battery (W).
        t_amb: outdoor ambient temperature (°C).
        c_batt: battery thermal capacity (J/K).
        Returns (t_shelter, t_batt).
        """
        # Heat exchange between battery and shelter air (positive = heat flowing into battery)
        q_batt_exchange = self.ha_batt * (self.t_shelter - self.t_batt)

        # 1. Update Battery Temperature
        # dT_batt/dt = (p_batt_heat + q_batt_exchange) / c_batt
        dT_batt = (p_batt_heat_w + q_batt_exchange) * dt_s / c_batt
        self.t_batt += dT_batt

        # 2. Update Shelter Air Temperature
        # Heat transfer through shelter envelope to outside (positive = heat loss from shelter to outside)
        q_envelope_loss = self.ua * (self.t_shelter - t_amb)

        # Net thermal influx into shelter before active HVAC cooling
        net_inflow_w = p_in_heat_w - q_batt_exchange - q_envelope_loss

        if grid_up:
            # HVAC is operating on AC mains. Active cooling removes heat to reach t_setpoint.
            # Thermostatic cooling demand to reach and hold t_setpoint
            cooling_demand_w = max(0.0, (self.t_shelter - self.t_setpoint) * self.c_shelter / dt_s + net_inflow_w)
            q_hvac = min(self.hvac_kw * 1000.0, cooling_demand_w)
        else:
            # During outage, active HVAC compressor drops offline
            q_hvac = 0.0

        # dT_shelter/dt = (net_inflow_w - q_hvac) / c_shelter
        dT_shelter = (net_inflow_w - q_hvac) * dt_s / self.c_shelter
        self.t_shelter += dT_shelter

        return self.t_shelter, self.t_batt

    def steady_state_temp(self, p_in_heat_w: float, t_amb: float) -> float:
        """Calculates theoretical passive steady-state shelter temperature: T_ss = T_amb + P / UA."""
        return t_amb + p_in_heat_w / self.ua

    def is_warning(self) -> bool:
        """True if battery temperature exceeds IEEE derating warning threshold (40°C)."""
        return self.t_batt >= T_WARN

    def is_critical(self) -> bool:
        """True if battery temperature exceeds Safety Arbiter critical shutdown threshold (50°C)."""
        return self.t_batt >= T_CRIT
